CREATE SEQUENCE CONVERSATION_SEQ START WITH 1000 INCREMENT BY 1;

CREATE TABLE CONVERSATION (
      RECORD_ID BIGSERIAL PRIMARY KEY,
      CONVERSATION_ID VARCHAR(20) NOT NULL UNIQUE,
      USER1_ID VARCHAR(20) NOT NULL,
      USER2_ID VARCHAR(20) NOT NULL,
      STATUS VARCHAR(10) DEFAULT 'ACTIVE',
      CRUD_VALUE VARCHAR(20) NOT NULL,
      LOCAL_TS   TIMESTAMP   NOT NULL,
      HOST_TS    TIMESTAMP   NOT NULL,
      UUID       UUID        NOT NULL
);

CREATE UNIQUE INDEX CVST_01 ON CONVERSATION(USER1_ID,USER2_ID);
