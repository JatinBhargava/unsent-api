CREATE SEQUENCE MESSAGES_SEQ START WITH 1000 INCREMENT BY 1;

CREATE TABLE MESSAGES (
      RECORD_ID BIGSERIAL PRIMARY KEY,
      MESSAGE_ID VARCHAR(20) NOT NULL UNIQUE,
      CONVERSATION_ID VARCHAR(20) NOT NULL,
      SENDER_ID VARCHAR(20) NOT NULL,
      MESSAGE_TEXT TEXT NOT NULL,
      IS_READ BOOLEAN DEFAULT FALSE,
      STATUS VARCHAR(10) DEFAULT 'A',
      CRUD_VALUE VARCHAR(20) NOT NULL,
      LOCAL_TS   TIMESTAMP   NOT NULL,
      HOST_TS    TIMESTAMP   NOT NULL,
      UUID       UUID        NOT NULL,
);

CREATE INDEX IDX_MSG_01 ON MESSAGES(SENDER_ID);
